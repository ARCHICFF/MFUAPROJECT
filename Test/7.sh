#!/bin/bash
# Скрипт ищет файлы по расширению в текущей директории

read -p "Введите расширение файлов для поиска (например, txt): " ext

# Убираем точку, если пользователь её ввёл
ext="${ext#.}"

results=$(find . -maxdepth 1 -type f -iname "*.$ext")

if [ -z "$results" ]; then
    echo "Файлы с расширением .$ext не найдены в текущей директории."
else
    echo "Найденные файлы с расширением .$ext:"
    echo "$results"
fi
